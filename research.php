<div class="shell section" id="methodology">
  <p class="eyebrow">Evaluation methods</p>
  <h2 class="mt-2">How the Evidence Was Gathered</h2>
  <p class="lede mt-2">The instruments are set out in Chapter 0 &sect;&thinsp;0.3.6. Two were administered
    to students and four to the faculty themselves.</p>
  <div class="grid grid--auto mt-5">
    <article class="card"><h3>Baseline first</h3><p>Each institution ran a baseline offering with no
      intervention before running the PDC one, so the comparison is within an institution rather than
      across them &mdash; different calendars, class sizes and student populations never have to be
      treated as equivalent.</p></article>
    <article class="card"><h3>Student survey &mdash; pre and post</h3><p>A common instrument on experience
      with and attitudes toward PDC, given at the start and end of the course by both development and
      testing team instructors. Because every site ran the same items, results can be pooled.</p></article>
    <article class="card"><h3>Assignment surveys</h3><p>After each lab and programming assignment: how much
      time it took, which days it was worked on, what was learned, the hardest part, what remained unclear,
      and how much it was enjoyed. This is what turns a chapter&rsquo;s timing tables into something an
      adopter can plan against.</p></article>
    <article class="card"><h3>Faculty, before selection</h3><p>Applicants&rsquo; PDC background, current use
      of PDC in class, institution, courses and student population &mdash; alongside a subjective read on
      their attitude to putting PDC in lower-level classes.</p></article>
    <article class="card"><h3>Faculty, after selection</h3><p>Whether the exemplars were appropriate and
      effective, how likely PDC is to reach their other courses, and their first ideas about approach and
      intervention points.</p></article>
    <article class="card"><h3>Faculty, annually and after</h3><p>Annual surveys during the summer working
      sessions counted students actually taught and how far PDC had been incorporated; a post-adoption
      survey asked whether the interventions will be retained, reduced or expanded, and what new directions
      followed.</p></article>
    <article class="card"><h3>IRB and local research questions</h3><p>Each testing team applied for IRB
      approval and set its own research questions, with data collection coordinated across teams from the
      start so the results could still be compared.</p></article>
    <article class="card"><h3>Analysis</h3><p>Matched pre/post responses with non-parametric Wilcoxon
      signed-rank tests and Cliff&rsquo;s delta for effect size, reported per item; open responses coded
      thematically, so the numbers come with student reasoning attached.</p></article>
    <article class="card"><h3>Effort measured honestly</h3><p>Developing examples, finding curriculum
      insertion points, revising assignments and testing software took more than 100 hours across the
      initial development year &mdash; reported rather than glossed over, because adopters need to plan
      for it.</p></article>
  </div>
