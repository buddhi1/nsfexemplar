<!-- ─────────────────────────────────────────────────────── methodology ── -->
<div class="shell section" id="methodology">
  <p class="eyebrow">Evaluation methods</p>
  <h2 class="mt-2">How the Evidence Was Gathered</h2>
  <div class="grid grid--auto mt-5">
    <article class="card"><h4>Baseline first</h4><p>For both CS1 and CS2, data was obtained for a baseline
      offering with no intervention, then again after PDC ideas were introduced &mdash; an experimental
      control within each institution rather than across them.</p></article>
    <article class="card"><h4>Shared instruments</h4><p>Common pre- and post-course surveys captured student
      background, self-reported experience with computing and with PDC topics, interest, perceived importance
      and understanding &mdash; enabling cross-team analysis.</p></article>
    <article class="card"><h4>Activity-level assessment</h4><p>Individual activities added pre/post quizzes
      and an adapted ASPECT engagement instrument, so a single activity&rsquo;s effect can be separated from
      the course as a whole.</p></article>
    <article class="card"><h4>Paired statistics</h4><p>Matched pre/post responses analyzed with
      non-parametric Wilcoxon signed-rank tests, with Cliff&rsquo;s delta reported for effect size and
      interpreted as negligible, small, medium or large.</p></article>
    <article class="card"><h4>Qualitative coding</h4><p>Thematic analysis of open-response questions
      alongside the quantitative results, so the numbers come with student reasoning attached.</p></article>
    <article class="card"><h4>IRB throughout</h4><p>Each testing team applied for IRB approval and developed
      institution-specific research questions, with coordinated data collection designed for cross-team
      comparison from the start.</p></article>
    <article class="card"><h4>Faculty instruments too</h4><p>Pre-selection, post-selection, annual and
      post-adoption surveys of the faculty themselves &mdash; capturing prior PDC background, the perceived
      effectiveness of the exemplars, students actually taught, and whether the interventions will be
      retained, reduced or expanded.</p></article>
    <article class="card"><h4>Effort measured honestly</h4><p>Developing examples, finding curriculum
      insertion points, revising assignments and testing software took more than 100 hours across the initial
      development year &mdash; reported rather than glossed over, because adopters need to plan for it.</p></article>
  </div>
</div>

